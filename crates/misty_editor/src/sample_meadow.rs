/// A group of trees around a point given from the camera: `bearing` degrees right of the view
/// (+Z), `distance` metres, `count` trees within `spread` metres, drawn from `kinds`
/// (prototype indices of [`tree_assets`]).
struct Grove {
    bearing: f32,
    distance: f32,
    count: usize,
    spread: f32,
    kinds: &'static [u16],
}

const fn grove(
    bearing: f32,
    distance: f32,
    count: usize,
    spread: f32,
    kinds: &'static [u16],
) -> Grove {
    Grove {
        bearing,
        distance,
        count,
        spread,
        kinds,
    }
}


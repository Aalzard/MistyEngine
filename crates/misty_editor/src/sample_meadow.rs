/// Side of the generated thatch textures in pixels (they tile).
const THATCH_SIZE: u32 = 1024;

/// Tileable value noise 0..1 with `cells` lattice cells across the tile.
fn tile_noise(u: f32, v: f32, cells: u32, seed: u32) -> f32 {
    let (x, y) = (u * cells as f32, v * cells as f32);
    let (ix, iy) = (x.floor() as i32, y.floor() as i32);
    let (fx, fy) = (x - ix as f32, y - iy as f32);
    let c = cells as i32;
    let h = |a: i32, b: i32| noise::hash(a.rem_euclid(c), b.rem_euclid(c), seed);
    let s = |t: f32| t * t * (3.0 - 2.0 * t);
    let (sx, sy) = (s(fx), s(fy));
    let top = h(ix, iy) + (h(ix + 1, iy) - h(ix, iy)) * sx;
    let bottom = h(ix, iy + 1) + (h(ix + 1, iy + 1) - h(ix, iy + 1)) * sx;
    top + (bottom - top) * sy
}

/// Meadow floor under the grass, top down, tileable: dark crumbly soil with damp patches and
/// moss, small pebbles and twigs, half buried under a litter of dead blades and thatch
/// (straw, olive and a few green strands) lying in every direction. Albedo (sRGB), height
/// and a tangent-space normal map from the height.
fn thatch() -> [RgbaImage; 3] {
    let n = THATCH_SIZE as usize;
    let mut color = vec![[0.0f32; 3]; n * n];
    let mut height = vec![0.0f32; n * n];
    for y in 0..n {
        for x in 0..n {
            let (u, v) = (x as f32 / n as f32, y as f32 / n as f32);
            let big = tile_noise(u, v, 6, 3) * 0.6 + tile_noise(u, v, 23, 4) * 0.4;
            let fine = tile_noise(u, v, 97, 5);
            let crumb = tile_noise(u, v, 211, 9);
            let moss = ((tile_noise(u, v, 11, 6) - 0.6) * 4.0).clamp(0.0, 1.0);
            // Damp, darker soil in hollows.
            let damp = ((0.5 - big) * 3.0).clamp(0.0, 1.0);
            let soil = [0.16, 0.115, 0.07]
                .map(|c| c * (0.7 + 0.5 * big) * (0.75 + 0.5 * crumb) * (1.0 - 0.35 * damp));
            let green = [0.1, 0.15, 0.04];
            color[y * n + x] = std::array::from_fn(|i| soil[i] + (green[i] - soil[i]) * moss);
            height[y * n + x] = 0.15 * big + 0.05 * fine + 0.04 * crumb + 0.03 * moss;
        }
    }
    // Small pebbles (4–12 mm on the 2.2 m tile), domed, partly sunk in the soil.
    for k in 0..1400 {
        let r = |salt: u32| noise::hash(k, salt as i32, 0x5eb1);
        let (cx, cy) = (r(1) * n as f32, r(2) * n as f32);
        let radius = 2.0 + 4.0 * r(3) * r(3);
        let tone = 0.75 + 0.5 * r(4);
        let base = [0.33, 0.3, 0.26].map(|c| c * tone);
        let reach = radius.ceil() as i32 + 1;
        for oy in -reach..=reach {
            for ox in -reach..=reach {
                let d = ((ox * ox + oy * oy) as f32).sqrt() / radius;
                if d > 1.0 {
                    continue;
                }
                let px = (cx as i32 + ox).rem_euclid(n as i32) as usize;
                let py = (cy as i32 + oy).rem_euclid(n as i32) as usize;
                let i = py * n + px;
                let h = 0.2 + 0.12 * (1.0 - d * d).sqrt();
                if h > height[i] {
                    height[i] = h;
                    // Lit from the top left, darker rim.
                    let lit = 1.0 - 0.3 * d * d + 0.1 * (-(ox + oy) as f32 / radius);
                    color[i] = base.map(|c| c * lit);
                }
            }
        }
    }
    // Strands, later ones on top: dead straw, olive half-dry blades, a few green ones.
    let strands = 10000;
    for k in 0..strands {
        let r = |salt: u32| noise::hash(k, salt as i32, 0x7a7c);
        let (x0, y0) = (r(1) * n as f32, r(2) * n as f32);
        let angle = r(3) * std::f32::consts::TAU;
        let length = 18.0 + 80.0 * r(4) * r(4);
        let width = 0.9 + 1.8 * r(5);
        let kind = r(6);
        let tone = 0.75 + 0.5 * r(7);
        let base = if kind < 0.06 {
            // Twigs.
            [0.17, 0.11, 0.06]
        } else if kind < 0.5 {
            [0.5, 0.42, 0.24]
        } else if kind < 0.8 {
            [0.38, 0.36, 0.16]
        } else {
            [0.28, 0.34, 0.11]
        };
        let top = 0.25 + 0.75 * k as f32 / strands as f32;
        let (dx, dy) = (angle.cos(), angle.sin());
        let bend = (r(8) - 0.5) * 0.02;
        let steps = (length * 2.0) as usize;
        for s in 0..steps {
            let t = s as f32 / steps as f32;
            let a = angle + bend * s as f32;
            let (cx, cy) = (
                x0 + dx * t * length + (a.cos() - dx) * t * length * 0.5,
                y0 + dy * t * length + (a.sin() - dy) * t * length * 0.5,
            );
            // Strands taper towards their tips and are darker where they dive under.
            let w = width * (1.0 - 0.6 * t);
            let shade = tone * (0.8 + 0.2 * (t * 9.0 + r(9) * 6.0).sin());
            let reach = w.ceil() as i32;
            for oy in -reach..=reach {
                for ox in -reach..=reach {
                    let d = ((ox * ox + oy * oy) as f32).sqrt() / w.max(0.5);
                    if d > 1.0 {
                        continue;
                    }
                    let px = (cx as i32 + ox).rem_euclid(n as i32) as usize;
                    let py = (cy as i32 + oy).rem_euclid(n as i32) as usize;
                    let h = top + 0.08 * (1.0 - d * d);
                    let i = py * n + px;
                    if h > height[i] {
                        height[i] = h;
                        let edge = 1.0 - 0.35 * d * d;
                        color[i] = base.map(|c| c * shade * edge);
                    }
                }
            }
        }
    }
    let srgb = |c: f32| {
        let c = c.clamp(0.0, 1.0);
        let s = if c <= 0.003_130_8 {
            c * 12.92
        } else {
            1.055 * c.powf(1.0 / 2.4) - 0.055
        };
        (s * 255.0).round() as u8
    };
    let size = THATCH_SIZE;
    let albedo = RgbaImage::from_fn(size, size, |x, y| {
        let c = color[y as usize * n + x as usize];
        image::Rgba([srgb(c[0]), srgb(c[1]), srgb(c[2]), 255])
    });
    let at = |x: i32, y: i32| {
        height[y.rem_euclid(n as i32) as usize * n + x.rem_euclid(n as i32) as usize]
    };
    let heights = RgbaImage::from_fn(size, size, |x, y| {
        let h = (at(x as i32, y as i32) * 255.0).round().clamp(0.0, 255.0) as u8;
        image::Rgba([h, h, h, 255])
    });
    let normal = RgbaImage::from_fn(size, size, |x, y| {
        let (x, y) = (x as i32, y as i32);
        let strength = 9.0;
        let ddx = (at(x + 1, y) - at(x - 1, y)) * strength;
        let ddy = (at(x, y + 1) - at(x, y - 1)) * strength;
        let v = Vec3::new(-ddx, ddy, 1.0).normalize();
        let enc = |c: f32| ((c * 0.5 + 0.5) * 255.0).round() as u8;
        image::Rgba([enc(v.x), enc(v.y), enc(v.z), 255])
    });
    [albedo, heights, normal]
}

fn terrain_data() -> TerrainData {
    let mut d = TerrainData::new(513, SIZE, 512);
    let s = d.spacing();
    for iz in 0..d.heightmap_resolution {
        for ix in 0..d.heightmap_resolution {
            d.set_height(ix, iz, height(ix as f32 * s.x, iz as f32 * s.y));
        }
    }
    d.layers = vec![
        TerrainLayer {
            name: "Meadow Ground".into(),
            diffuse: Some(GROUND.into()),
            normal_map: Some(GROUND_NORMAL.into()),
            height_map: Some(GROUND_HEIGHT.into()),
            normal_scale: 1.0,
            tile_size: [2.2, 2.2],
            smoothness: 0.05,
            rules: rules([0.0, 22.0], 0),
            ..Default::default()
        },
        TerrainLayer {
            name: "Scree".into(),
            diffuse: Some(SCREE.into()),
            tile_size: [8.0, 8.0],
            rules: rules([20.0, 34.0], 1),
            ..Default::default()
        },
        TerrainLayer {
            name: "Cliff".into(),
            diffuse: Some(ROCK.into()),
            normal_map: Some(ROCK_NORMAL.into()),
            tile_size: [40.0, 40.0],
            rules: rules([34.0, 90.0], 2),
            ..Default::default()
        },
    ];
    d.rule_seed = 7;
    d.details = grass();
    auto_paint::generate(&mut d);
    details::generate(&mut d);
    d
}

fn ground(d: &TerrainData, x: f32, z: f32) -> f32 {
    CORNER.y + d.sample_height(x - CORNER.x, z - CORNER.z)
}

fn volume() -> PostProcessVolume {
    let mut v = PostProcessVolume::default();
    v.tonemapping.active = true;
    v.tonemapping.mode = TonemapMode::Aces;
    v.bloom.active = true;
    v.bloom.intensity = 0.35;
    v.bloom.threshold = 1.1;
    v.color_adjustments.active = true;
    v.color_adjustments.post_exposure = 0.35;
    v.color_adjustments.contrast = -4.0;
    v.color_adjustments.saturation = 4.0;
    v.ambient_occlusion.active = true;
    let cs = &mut v.contact_shadows;
    cs.active = true;
    cs.length = 0.12;
    cs.distance_fade = 16.0;
    cs.opacity = 0.3;
    cs.sample_count = 6;
    let c = &mut v.clouds;
    c.active = true;
    CloudPreset::Cloudy.apply(c);
    c.coverage = 0.5;
    c.density = 0.7;
    c.wind_direction = 100.0;
    c.wind_speed = 12.0;
    c.silver_lining = 0.9;
    c.shadow_opacity = 0.6;
    let f = &mut v.fog;
    f.active = true;
    f.max_fog_distance = 3000.0;
    f.attenuation_distance = 6000.0;
    f.base_height = 0.0;
    f.maximum_height = 150.0;
    // Gentle forward haze: the field stays green-gold to the mountains against the sun.
    f.anisotropy = 0.3;
    f.volumetric_distance = 250.0;
    v.sun_shafts.active = true;
    v.sun_shafts.intensity = 0.5;
    v
}

fn demo_scene(d: &TerrainData) -> Scene {
    let mut s = Scene::default_3d("MeadowDemo");
    let eye = (CORNER.x + EYE.0, CORNER.z + EYE.1);
    if let Some(cam) = s.find_by_name("Main Camera") {
        let y = ground(d, eye.0, eye.1) + 1.6;
        s.set_transform(
            cam,
            Transform::from_position(Vec3::new(eye.0, y, eye.1))
                .with_euler(Vec3::new(-4.0, 0.0, 0.0)),
        );
        let mut c = s
            .world
            .get::<&mut misty_engine::scene::Camera>(cam)
            .unwrap();
        c.far = 5000.0;
        c.near = 0.05;
        c.fov = 62.0;
    }
    if let Some(sun) = s.find_by_name("Directional Light") {
        // Low afternoon sun ahead of the camera, to the right: the grass is backlit.
        s.set_transform(
            sun,
            Transform::from_position(Vec3::new(0.0, 200.0, 0.0))
                .with_euler(Vec3::new(30.0, 205.0, 0.0)),
        );
        let mut l = s.world.get::<&mut Light>(sun).unwrap();
        l.color = [1.0, 0.91, 0.76];
        l.intensity = 2.4;
        l.shadows = Shadows::Soft;
        // Blades shade the turf at their feet (screen-space, the first centimetres).
        l.contact_shadows = true;
    }
    let rs = &mut s.render_settings;
    rs.skybox.sun_disk = SunDisk::HighQuality;
    rs.skybox.sun_size = 0.04;
    rs.skybox.atmosphere_thickness = 1.0;

    let terrain = s.spawn("Terrain", None);
    s.set_transform(terrain, Transform::from_position(CORNER));
    s.add(
        terrain,
        Terrain {
            terrain_data: DATA.into(),
            ..Default::default()
        },
    );
    s.add(terrain, TerrainCollider::default());
    let fx = s.spawn("Global Volume", None);
    s.add(fx, volume());
    // Wind across the field from the left, slightly away from the camera.
    let wind = s.spawn("Wind Zone", None);
    s.set_transform(
        wind,
        Transform::from_position(Vec3::new(CORNER.x + EYE.0, 10.0, CORNER.z + EYE.1))
            .with_euler(Vec3::new(0.0, 75.0, 0.0)),
    );
    s.add(wind, WindZone::default());
    s
}

#[test]
#[ignore = "writes into SampleProject; run on purpose to regenerate"]
fn write_meadow_demo() {
    let root = project();
    let [albedo, height, normal] = thatch();
    for (rel, img) in [
        (GROUND, albedo),
        (GROUND_HEIGHT, height),
        (GROUND_NORMAL, normal),
    ] {
        img.save(root.join(rel)).unwrap();
    }
    let d = terrain_data();
    d.save(&root.join(DATA)).unwrap();
    demo_scene(&d).save(&root.join(SCENE)).unwrap();
}

#[test]
fn meadow_demo_matches_its_generator() {
    let root = project();
    for rel in [
        GROUND,
        GROUND_NORMAL,
        GROUND_HEIGHT,
        SCREE,
        ROCK,
        ROCK_NORMAL,
    ] {
        assert!(root.join(rel).exists(), "{rel}");
    }
    let on_disk = TerrainData::load(&root.join(DATA)).unwrap();
    let generated = terrain_data();
    assert_eq!(on_disk.layers, generated.layers);
    assert_eq!(on_disk.details, generated.details);
    assert_eq!(on_disk.size, generated.size);
    for (a, b) in on_disk.heights.iter().zip(&generated.heights) {
        assert!((a - b).abs() < 3.0 / 65535.0);
    }
    let (scene, report) = Scene::load(&root.join(SCENE)).unwrap();
    assert!(report.warnings.is_empty(), "{:?}", report.warnings);
    assert_eq!(scene.to_json(), demo_scene(&generated).to_json());
    // Dense grass all around the camera.
    let lo = glam::Vec2::new(EYE.0 - 8.0, EYE.1);
    let blades = details::scatter(&generated, lo, lo + 16.0);
    assert!(blades.len() > 40_000, "{}", blades.len());
    assert!(blades.iter().any(|b| b.seed_head()), "seed heads");
}

/// Playing works (no scripts; the terrain collider builds).
#[test]
fn meadow_demo_plays() {
    let root = project();
    let data = TerrainData::load(&root.join(DATA)).unwrap();
    let scene = demo_scene(&data);
    let terrain = scene.find_by_name("Terrain").unwrap();
    scene
        .world
        .get::<&mut Terrain>(terrain)
        .unwrap()
        .terrain_data = root.join(DATA).to_string_lossy().into_owned();
    let physics = misty_engine::physics::Physics::build(&scene, Vec3::new(0.0, -9.81, 0.0));
    assert!(physics.warnings.is_empty(), "{:?}", physics.warnings);
}

/// Trees of the meadow (deterministic): every grove's trees, on gentle ground only, never
/// within 9 m of each other or in the open view ahead of the player.
fn trees(d: &TerrainData) -> Vec<TreeInstance> {
    let eye = glam::Vec2::new(EYE.0, EYE.1);
    let mut out: Vec<TreeInstance> = Vec::new();
    let mut n = 0i32;
    for (g, grove) in GROVES.iter().enumerate() {
        let a = grove.bearing.to_radians();
        let center = eye + glam::Vec2::new(a.sin(), a.cos()) * grove.distance;
        let mut placed = 0;
        for k in 0..grove.count * 12 {
            if placed == grove.count {
                break;
            }
            n += 1;
            let r = |salt| noise::hash(n, salt, 0x7ee5);
            // Denser towards the grove's middle.
            let (angle, dist) = (r(1) * std::f32::consts::TAU, r(2).sqrt() * grove.spread);
            let p = if k == 0 && grove.count == 1 {
                center
            } else {
                center + glam::Vec2::new(angle.cos(), angle.sin()) * dist
            };
            // The open view: nothing within 22° of straight ahead closer than 450 m.
            let rel = p - eye;
            if rel.x.atan2(rel.y).to_degrees().abs() < 22.0 && rel.length() < 450.0 {
                continue;
            }
            let inside = p.cmpge(glam::Vec2::splat(10.0)).all()
                && p.cmple(glam::Vec2::new(d.size.x, d.size.z) - 10.0).all();
            if !inside || misty_engine::terrain::trees::slope_at(d, p.x, p.y) > 20.0 {
                continue;
            }
            let crowded = out.iter().any(|t| {
                let q = t.position * glam::Vec2::new(d.size.x, d.size.z);
                q.distance(p) < 9.0
            });
            if crowded {
                continue;
            }
            let kind = grove.kinds[(placed + g) % grove.kinds.len()];
            let height = 0.82 + 0.36 * r(3);
            out.push(TreeInstance {
                position: glam::Vec2::new(p.x / d.size.x, p.y / d.size.z),
                prototype: kind,
                rotation: r(4) * std::f32::consts::TAU,
                height_scale: height,
                width_scale: (0.88 + 0.24 * r(5)) * height.powf(0.3),
                color: r(6),
            });
            placed += 1;
        }
    }
    out
}

fn terrain_data() -> TerrainData {
    let mut d = TerrainData::new(513, SIZE, 512);
    let s = d.spacing();
    for iz in 0..d.heightmap_resolution {
        for ix in 0..d.heightmap_resolution {
            d.set_height(ix, iz, height(ix as f32 * s.x, iz as f32 * s.y));
        }
    }
    d.layers = vec![
        TerrainLayer {
            name: "Meadow Ground".into(),
            diffuse: Some(GROUND.into()),
            normal_map: Some(GROUND_NORMAL.into()),
            height_map: Some(GROUND_HEIGHT.into()),
            normal_scale: 1.0,
            tile_size: [2.2, 2.2],
            smoothness: 0.05,
            rules: rules([0.0, 22.0], 0),
            ..Default::default()
        },
        TerrainLayer {
            name: "Scree".into(),
            diffuse: Some(SCREE.into()),
            tile_size: [8.0, 8.0],
            rules: rules([20.0, 34.0], 1),
            ..Default::default()
        },
        TerrainLayer {
            name: "Cliff".into(),
            diffuse: Some(ROCK.into()),
            normal_map: Some(ROCK_NORMAL.into()),
            tile_size: [40.0, 40.0],
            rules: rules([34.0, 90.0], 2),
            ..Default::default()
        },
    ];
    d.rule_seed = 7;
    d.details = grass();
    auto_paint::generate(&mut d);
    details::generate(&mut d);
    d.trees.prototypes = tree_assets()
        .into_iter()
        .map(|(path, _)| TreePrototype { tree: path.into() })
        .collect();
    // Placed on the heights as stored (16 bits), so the file and the generator agree.
    let stored = TerrainData {
        heights: d
            .heights
            .iter()
            .map(|h| (h * 65535.0).round() / 65535.0)
            .collect(),
        ..d.clone()
    };
    d.trees.instances = trees(&stored);
    d
}

fn ground(d: &TerrainData, x: f32, z: f32) -> f32 {
    CORNER.y + d.sample_height(x - CORNER.x, z - CORNER.z)
}

fn volume() -> PostProcessVolume {
    let mut v = PostProcessVolume::default();
    v.tonemapping.active = true;
    v.tonemapping.mode = TonemapMode::Aces;
    v.bloom.active = true;
    v.bloom.intensity = 0.35;
    v.bloom.threshold = 1.1;
    v.color_adjustments.active = true;
    v.color_adjustments.post_exposure = 0.35;
    v.color_adjustments.contrast = -4.0;
    v.color_adjustments.saturation = 4.0;
    v.ambient_occlusion.active = true;
    let cs = &mut v.contact_shadows;
    cs.active = true;
    cs.length = 0.12;
    cs.distance_fade = 16.0;
    cs.opacity = 0.3;
    cs.sample_count = 6;
    let c = &mut v.clouds;
    c.active = true;
    CloudPreset::Cloudy.apply(c);
    c.coverage = 0.5;
    c.density = 0.7;
    c.wind_direction = 100.0;
    c.wind_speed = 12.0;
    c.silver_lining = 0.9;
    c.shadow_opacity = 0.6;
    let f = &mut v.fog;
    f.active = true;
    f.max_fog_distance = 3000.0;
    f.attenuation_distance = 6000.0;
    f.base_height = 0.0;
    f.maximum_height = 150.0;
    // Gentle forward haze: the field stays green-gold to the mountains against the sun.
    f.anisotropy = 0.3;
    f.volumetric_distance = 250.0;
    v.sun_shafts.active = true;
    v.sun_shafts.intensity = 0.5;
    v
}

fn demo_scene(d: &TerrainData) -> Scene {
    let mut s = Scene::default_3d("MeadowDemo");
    let eye = (CORNER.x + EYE.0, CORNER.z + EYE.1);
    if let Some(cam) = s.find_by_name("Main Camera") {
        let y = ground(d, eye.0, eye.1) + 1.6;
        s.set_transform(
            cam,
            Transform::from_position(Vec3::new(eye.0, y, eye.1))
                .with_euler(Vec3::new(-4.0, 0.0, 0.0)),
        );
        let mut c = s
            .world
            .get::<&mut misty_engine::scene::Camera>(cam)
            .unwrap();
        c.far = 5000.0;
        c.near = 0.05;
        c.fov = 62.0;
    }
    if let Some(sun) = s.find_by_name("Directional Light") {
        // Low afternoon sun ahead of the camera, to the right: the grass is backlit.
        s.set_transform(
            sun,
            Transform::from_position(Vec3::new(0.0, 200.0, 0.0))
                .with_euler(Vec3::new(30.0, 205.0, 0.0)),
        );
        let mut l = s.world.get::<&mut Light>(sun).unwrap();
        l.color = [1.0, 0.91, 0.76];
        l.intensity = 2.4;
        l.shadows = Shadows::Soft;
        // Blades shade the turf at their feet (screen-space, the first centimetres).
        l.contact_shadows = true;
    }
    let rs = &mut s.render_settings;
    rs.skybox.sun_disk = SunDisk::HighQuality;
    rs.skybox.sun_size = 0.04;
    rs.skybox.atmosphere_thickness = 1.0;

    let terrain = s.spawn("Terrain", None);
    s.set_transform(terrain, Transform::from_position(CORNER));
    s.add(
        terrain,
        Terrain {
            terrain_data: DATA.into(),
            ..Default::default()
        },
    );
    s.add(terrain, TerrainCollider::default());
    let fx = s.spawn("Global Volume", None);
    s.add(fx, volume());
    // Wind across the field from the left, slightly away from the camera.
    let wind = s.spawn("Wind Zone", None);
    s.set_transform(
        wind,
        Transform::from_position(Vec3::new(CORNER.x + EYE.0, 10.0, CORNER.z + EYE.1))
            .with_euler(Vec3::new(0.0, 75.0, 0.0)),
    );
    s.add(wind, WindZone::default());
    // The First Person Player (the sample prefab, as tuned) stands in the field; its camera
    // replaces the Main Camera (kept, switched off).
    let prefab =
        misty_engine::scene::prefab::Prefab::load(&project().join(crate::fps_player::PREFAB))
            .expect("First Person Player prefab");
    let player = s.instantiate_prefab(&prefab, Some(crate::fps_player::PREFAB), None);
    s.set_transform(player, Transform::from_position(PLAYER));
    // The player's camera sees the whole basin (2 km, as set in the scene).
    if let Some(cam) = s.find_by_name("Camera") {
        s.world
            .get::<&mut misty_engine::scene::Camera>(cam)
            .unwrap()
            .far = 2000.0;
    }
    if let Some(cam) = s.find_by_name("Main Camera") {
        s.game_object_mut(cam).active = false;
    }
    s
}


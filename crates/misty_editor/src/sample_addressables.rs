fn script(path: &str) -> Scripts {
    Scripts {
        list: vec![ScriptRef {
            path: path.into(),
            ..Default::default()
        }],
    }
}

/// A one-object (plus children) prefab of primitives.
fn prop(name: &str, parts: &[(PrimitiveMesh, Transform, &str)], behaviour: Option<&str>) -> Prefab {
    let mut s = Scene::new(name);
    let root = s.spawn(name, None);
    for (i, (mesh, t, mat)) in parts.iter().enumerate() {
        let e = if i == 0 {
            root
        } else {
            s.spawn(&format!("{name} Part {i}"), Some(root))
        };
        s.set_transform(e, *t);
        s.add(e, MeshFilter::primitive(*mesh));
        s.add(
            e,
            MeshRenderer {
                material: Some((*mat).into()),
                ..Default::default()
            },
        );
    }
    if let Some(b) = behaviour {
        s.add(root, script(b));
    }
    Prefab::from_scene(&s, root)
}


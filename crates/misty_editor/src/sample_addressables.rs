/// `Transform` with a scale, builder style.
trait WithScale {
    fn with_scale(self, scale: Vec3) -> Self;
}

impl WithScale for Transform {
    fn with_scale(mut self, scale: Vec3) -> Self {
        self.scale = scale;
        self
    }
}


#[test]
fn addressables_demo_loads_simulated_and_built_bundles() {
    let root = project();
    let s = settings();
    let plan = misty_engine::asset_groups::catalog::plan(&root, &s, "windows-x64");
    assert!(plan.missing.is_empty(), "{:?}", plan.missing);
    assert!(plan.duplicates().is_empty(), "{:?}", plan.duplicates());
    check_demo(Some(Provider::Simulated(plan.catalog)));

    let out = temp_out();
    let built =
        misty_engine::asset_groups::build::build_bundles(&root, &s, "windows-x64", &out).unwrap();
    assert_eq!(built.catalog.bundles.len(), 2);
    check_demo(Some(Provider::Bundles {
        catalog: built.catalog,
        local_dir: out.clone(),
        cache_dir: out.join("cache"),
    }));
}

fn temp_out() -> PathBuf {
    let n = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let p = std::env::temp_dir().join(format!("misty_addr_demo_{n}"));
    std::fs::create_dir_all(&p).unwrap();
    p
}

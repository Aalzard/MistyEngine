//! The reference as Markdown and as one static HTML page (inline styles, a filter box).

use super::{DocEntry, Kind, Section};

const INTRO: &str = "Generated by `misty --api-docs docs/api` from the engine's Lua bindings \
(`crates/misty_engine/src/scripting`) and the Code Editor's autocomplete tables. Do not edit by \
hand: a test fails when this file no longer matches the bindings.";

fn kind_label(e: &DocEntry) -> &'static str {
    match (e.kind, e.settable) {
        (Kind::Function, _) => "function",
        (Kind::Property, true) => "property (read / write)",
        (Kind::Property, false) => "property",
    }
}

pub fn markdown(sections: &[Section]) -> String {
    let mut out = String::new();
    out.push_str("# Misty Engine Lua API\n\n");
    out.push_str(INTRO);
    out.push_str("\n\n");
    let total: usize = sections.iter().map(|s| s.entries.len()).sum();
    out.push_str(&format!(
        "{} members in {} sections.\n\n## Contents\n\n",
        total,
        sections.len()
    ));
    for s in sections {
        out.push_str(&format!("- [{}](#{})\n", s.title, s.anchor()));
    }
    for s in sections {
        out.push_str(&format!(
            "\n<a id=\"{}\"></a>\n\n## {}\n\n",
            s.anchor(),
            s.title
        ));
        if !s.description.is_empty() {
            out.push_str(&format!("{}\n\n", s.description));
        }
        for e in &s.entries {
            out.push_str(&format!("### `{}`\n\n", e.signature));
            out.push_str(&format!("*{}*", kind_label(e)));
            if !e.source.is_empty() {
                out.push_str(&format!(" · source: `{}`", e.source));
            }
            out.push_str("\n\n");
            if !e.summary.is_empty() {
                out.push_str(&format!("{}\n\n", e.summary));
            }
            if !e.notes.is_empty() && e.notes != e.summary {
                out.push_str(&format!("> {}\n\n", e.notes));
            }
        }
    }
    out
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// `backticks` in doc text become <code>.
fn inline(s: &str) -> String {
    let mut out = String::new();
    for (i, part) in esc(s).split('`').enumerate() {
        if i % 2 == 1 {
            out.push_str("<code>");
            out.push_str(part);
            out.push_str("</code>");
        } else {
            out.push_str(part);
        }
    }
    out
}


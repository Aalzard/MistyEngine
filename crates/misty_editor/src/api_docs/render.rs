pub fn html(sections: &[Section]) -> String {
    let mut out = String::new();
    out.push_str("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
    out.push_str("<title>Misty Lua API</title>\n<style>");
    out.push_str(STYLE);
    out.push_str("</style>\n</head>\n<body>\n<nav aria-label=\"Sections\">\n");
    out.push_str("<h1>Misty Lua API</h1>\n");
    out.push_str(
        "<label for=\"filter\" class=\"meta\">Filter</label>\n\
         <input id=\"filter\" type=\"search\" placeholder=\"GetKey, position…\">\n<ul>\n",
    );
    for s in sections {
        out.push_str(&format!(
            "<li><a href=\"#{}\">{}</a></li>\n",
            s.anchor(),
            esc(&s.title)
        ));
    }
    out.push_str("</ul>\n</nav>\n<main>\n");
    out.push_str(&format!(
        "<p class=\"meta\">{}</p>\n",
        inline(super::render::INTRO)
    ));
    for s in sections {
        out.push_str(&format!(
            "<section id=\"{}\">\n<h2>{}</h2>\n",
            s.anchor(),
            esc(&s.title)
        ));
        if !s.description.is_empty() {
            out.push_str(&format!("<p>{}</p>\n", inline(&s.description)));
        }
        for e in &s.entries {
            let key = format!("{} {}", e.signature, e.summary).to_lowercase();
            out.push_str(&format!(
                "<div class=\"entry\" data-key=\"{}\">\n<div class=\"sig\">{}</div>\n",
                esc(&key),
                esc(&e.signature)
            ));
            let mut meta = kind_label(e).to_owned();
            if !e.source.is_empty() {
                meta.push_str(&format!(" · source: <code>{}</code>", esc(&e.source)));
            }
            out.push_str(&format!("<div class=\"meta\">{meta}</div>\n"));
            if !e.summary.is_empty() {
                out.push_str(&format!("<p>{}</p>\n", inline(&e.summary)));
            }
            if !e.notes.is_empty() && e.notes != e.summary {
                out.push_str(&format!("<p class=\"notes\">{}</p>\n", inline(&e.notes)));
            }
            out.push_str("</div>\n");
        }
        out.push_str("</section>\n");
    }
    out.push_str("</main>\n<script>");
    out.push_str(SCRIPT);
    out.push_str("</script>\n</body>\n</html>\n");
    out
}

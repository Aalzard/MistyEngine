//! Multi-scene sample in `SampleProject`: two scenes meant to be open together.
//! MultiSceneLevel is the level (ground, ramp and crates, no camera or light);
//! MultiSceneLighting holds the sun, the camera, an evening sky with fog and a Player capsule
//! that falls onto the level's ground. The level's Scene Loader script adds the lighting scene
//! additively when the level is played on its own. Regenerate with
//! `cargo test -p misty_editor -- --ignored write_multiscene_demo`; the other tests check the
//! committed files and play both scenes together.

use std::path::PathBuf;

use glam::Vec3;
use misty_engine::scene::render_settings::FogMode;
use misty_engine::scene::{
    Camera, CapsuleCollider, Light, MeshFilter, MeshRenderer, PrimitiveMesh, Rigidbody, Scene,
    ScriptRef, Scripts, Shadows, Transform,
};

const LEVEL: &str = "Assets/Scenes/MultiSceneLevel.scene";
const LIGHTING: &str = "Assets/Scenes/MultiSceneLighting.scene";
const LOADER: &str = "Assets/Scripts/AdditiveLoader.lua";
// Materials generated by the LightingDemo sample.
const SAND: &str = "Assets/Materials/Sand.mat";
const STONE: &str = "Assets/Materials/Sandstone.mat";
const METAL: &str = "Assets/Materials/Blue Steel.mat";

const LOADER_SOURCE: &str = r#"-- Adds a scene next to this one when it isn't open yet (play the level on its own and the
-- lighting / player scene comes with it).
local AdditiveLoader = { scene = "MultiSceneLighting" }

function AdditiveLoader:Start()
    if SceneManager.GetSceneByName(self.scene) == nil then
        SceneManager.LoadScene(self.scene, LoadSceneMode.Additive)
    end
end

return AdditiveLoader
"#;

fn project() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../SampleProject")
}

/// A mesh with a material and (optionally) a Box Collider.
fn solid(s: &mut Scene, name: &str, mesh: PrimitiveMesh, t: Transform, material: &str) {
    let e = s.spawn(name, None);
    s.set_transform(e, t);
    s.add(e, MeshFilter::primitive(mesh));
    s.add(
        e,
        MeshRenderer {
            material: Some(material.into()),
            ..Default::default()
        },
    );
    s.add_by_name(e, "Box Collider");
}

/// The level: ground, a ramp, a few crates and the Scene Loader.
fn level_scene() -> Scene {
    let mut s = Scene::new("MultiSceneLevel");
    let mut ground = Transform::from_position(Vec3::new(0.0, -0.5, 0.0));
    ground.scale = Vec3::new(24.0, 1.0, 24.0);
    solid(&mut s, "Ground", PrimitiveMesh::Cube, ground, SAND);
    let mut ramp =
        Transform::from_position(Vec3::new(4.0, 0.6, 3.0)).with_euler(Vec3::new(-15.0, -20.0, 0.0));
    ramp.scale = Vec3::new(3.0, 0.3, 6.0);
    solid(&mut s, "Ramp", PrimitiveMesh::Cube, ramp, STONE);
    for (i, (x, z, yaw)) in [(-3.0, 2.0, 10.0), (-4.2, 3.4, 35.0), (-2.4, 4.6, -20.0)]
        .into_iter()
        .enumerate()
    {
        let t = Transform::from_position(Vec3::new(x, 0.5, z)).with_euler(Vec3::new(0.0, yaw, 0.0));
        solid(
            &mut s,
            &format!("Crate {}", i + 1),
            PrimitiveMesh::Cube,
            t,
            STONE,
        );
    }
    let loader = s.spawn("Scene Loader", None);
    s.add(
        loader,
        Scripts {
            list: vec![ScriptRef {
                path: LOADER.into(),
                enabled: true,
                fields: Default::default(),
            }],
        },
    );
    s
}

/// Lighting and player: sun, camera, sky and fog, and a falling Player capsule.
fn lighting_scene() -> Scene {
    let mut s = Scene::new("MultiSceneLighting");
    let sun = s.spawn("Directional Light", None);
    s.set_transform(
        sun,
        Transform::from_position(Vec3::new(0.0, 6.0, 0.0)).with_euler(Vec3::new(28.0, -40.0, 0.0)),
    );
    s.add(
        sun,
        Light {
            color: [1.0, 0.78, 0.58],
            intensity: 1.3,
            shadows: Shadows::Soft,
            ..Light::directional()
        },
    );
    let cam = s.spawn("Main Camera", None);
    s.set_transform(
        cam,
        Transform::from_position(Vec3::new(0.0, 4.0, -10.0)).with_euler(Vec3::new(16.0, 0.0, 0.0)),
    );
    s.game_object_mut(cam).tag = "MainCamera".into();
    s.add(cam, Camera::default());
    s.add_by_name(cam, "Audio Listener");

    let player = s.spawn("Player", None);
    s.set_transform(player, Transform::from_position(Vec3::new(0.0, 4.0, 0.0)));
    s.add(player, MeshFilter::primitive(PrimitiveMesh::Capsule));
    s.add(
        player,
        MeshRenderer {
            material: Some(METAL.into()),
            ..Default::default()
        },
    );
    s.add(player, CapsuleCollider::default());
    s.add(
        player,
        Rigidbody {
            mass: 70.0,
            ..Default::default()
        },
    );

    let rs = &mut s.render_settings;
    rs.skybox.sky_tint = [0.56, 0.5, 0.52];
    rs.skybox.exposure = 1.15;
    rs.fog.enabled = true;
    rs.fog.color = [0.8, 0.66, 0.58];
    rs.fog.mode = FogMode::ExponentialSquared;
    rs.fog.density = 0.02;
    s
}

#[test]
#[ignore = "writes into SampleProject; run on purpose to regenerate"]
fn write_multiscene_demo() {
    let root = project();
    level_scene().save(&root.join(LEVEL)).unwrap();
    lighting_scene().save(&root.join(LIGHTING)).unwrap();
    std::fs::write(root.join(LOADER), LOADER_SOURCE).unwrap();
}

#[test]
fn multiscene_demo_matches_its_generator() {
    let root = project();
    for (rel, scene) in [(LEVEL, level_scene()), (LIGHTING, lighting_scene())] {
        let text = std::fs::read_to_string(root.join(rel)).unwrap();
        assert_eq!(
            text.replace("\r\n", "\n"),
            scene.to_json(),
            "regenerate with write_multiscene_demo"
        );
    }
    let script = std::fs::read_to_string(root.join(LOADER)).unwrap();
    assert_eq!(script.replace("\r\n", "\n"), LOADER_SOURCE);
    let build = misty_engine::build::BuildSettings::load(&root).unwrap();
    for rel in [LEVEL, LIGHTING] {
        assert!(
            build.scenes.iter().any(|s| s.path == rel),
            "{rel} in Build Settings"
        );
    }
}

/// Both scenes open together: the lighting scene is active, the player lands on the
/// level's ground, and each scene still saves only its own objects.
#[test]
fn multiscene_demo_plays_both_scenes_together() {
    let root = project();
    let (mut scene, report) = Scene::load(&root.join(LEVEL)).unwrap();
    assert!(report.warnings.is_empty(), "{:?}", report.warnings);
    scene.set_scene_path(0, LEVEL);
    let text = std::fs::read_to_string(root.join(LIGHTING)).unwrap();
    let (lighting, _, report) = scene.load_additive(LIGHTING, &text).unwrap();
    assert!(report.warnings.is_empty(), "{:?}", report.warnings);
    assert!(
        !scene.render_settings.fog.enabled,
        "the level is active first"
    );
    assert!(scene.set_active_scene(lighting));
    assert!(
        scene.render_settings.fog.enabled,
        "lighting comes from the active scene"
    );
    assert_eq!(scene.scene_to_json(0), level_scene().to_json());

    let settings = misty_engine::settings::ProjectSettings::default();
    let (audio, _) = misty_engine::audio::Audio::null(root.clone());
    let mut runtime = misty_engine::runtime::Runtime::start_with_audio(
        &mut scene,
        root.clone(),
        &settings,
        audio,
    );
    let mut time = misty_engine::runtime::Time::default();
    for _ in 0..120 {
        time.advance(1.0 / 60.0);
        runtime.update(&mut scene, &time, Default::default());
    }
    let player = scene.find_by_name("Player").unwrap();
    let y = scene.world_position(player).y;
    assert!(
        (0.8..1.3).contains(&y),
        "the player stands on the level's ground: {y}"
    );
    assert!(
        runtime.take_requests().is_empty(),
        "the loader sees the open scene"
    );
}

/// Playing only the level: its Scene Loader adds the lighting scene from the Build Settings.
#[test]
fn level_alone_loads_the_lighting_scene_additively() {
    let root = project();
    let (mut scene, _) = Scene::load(&root.join(LEVEL)).unwrap();
    scene.set_scene_path(0, LEVEL);
    let build = misty_engine::build::BuildSettings::load(&root).unwrap();
    let settings = misty_engine::settings::ProjectSettings::default();
    let (audio, _) = misty_engine::audio::Audio::null(root.clone());
    let mut runtime = misty_engine::runtime::Runtime::start_with_audio(
        &mut scene,
        root.clone(),
        &settings,
        audio,
    );
    let mut time = misty_engine::runtime::Time::default();
    time.advance(1.0 / 60.0);
    runtime.update(&mut scene, &time, Default::default());
    for r in runtime.take_requests() {
        runtime
            .apply_scene_request(&mut scene, &build, &root, &r)
            .unwrap();
    }
    assert_eq!(scene.loaded_scenes().len(), 2);
    assert!(scene.find_by_name("Player").is_some());
    assert_eq!(scene.scene_of(scene.find_by_name("Player").unwrap()), 1);
}

//! Reflection Probe Inspector: type and refresh, runtime settings (importance, intensity, box
//! projection, blend distance, box size/offset with Edit Bounding Volume), capture settings and
//! the bake / refresh buttons.

use egui::{RichText, Ui};
use glam::Vec3;
use misty_engine::hecs::Entity;
use misty_engine::scene::ReflectionProbe;
use misty_engine::scene::reflection_probe::{ProbeClearFlags, ProbeMode, RESOLUTIONS};

use super::editors::{color_rgb, combo, grid};
use crate::state::EditorState;
use crate::widgets::vec3_row;

pub const NAMES: [&str; 2] = ["Reflection Probe", "Reflection Probe Group"];

pub fn icon(name: &str) -> Option<&'static str> {
    NAMES.contains(&name).then_some("◍")
}

pub fn enabled_flag(state: &EditorState, e: Entity, name: &str) -> Option<bool> {
    (name == NAMES[0])
        .then(|| {
            state
                .scene
                .world
                .get::<&ReflectionProbe>(e)
                .ok()
                .map(|p| p.enabled)
        })
        .flatten()
}

pub fn set_enabled(state: &mut EditorState, e: Entity, name: &str, on: bool) {
    if name == NAMES[0] {
        let _ = state
            .scene
            .world
            .get::<&mut ReflectionProbe>(e)
            .map(|mut p| p.enabled = on);
    }
}

pub fn edit(ui: &mut Ui, state: &mut EditorState, e: Entity, name: &str) -> bool {
    if name != NAMES[0] {
        ui.weak("Generated by Lighting ▸ Generate Probes; its settings are edited there.");
        return false;
    }
    let Ok(mut p) = state
        .scene
        .world
        .get::<&ReflectionProbe>(e)
        .map(|c| (*c).clone())
    else {
        return false;
    };
    let ch = probe(ui, state, e, &mut p);
    if ch {
        let _ = state.scene.world.insert_one(e, p);
    }
    ch
}

fn row(ui: &mut Ui, label: &str, widget: impl FnOnce(&mut Ui) -> bool) -> bool {
    ui.label(label);
    let ch = widget(ui);
    ui.end_row();
    ch
}

fn drag(ui: &mut Ui, v: &mut f32, speed: f64, range: std::ops::RangeInclusive<f32>) -> bool {
    ui.add(
        egui::DragValue::new(v)
            .speed(speed)
            .range(range)
            .max_decimals(3),
    )
    .changed()
}

fn probe(ui: &mut Ui, state: &mut EditorState, e: Entity, p: &mut ReflectionProbe) -> bool {
    let mut ch = grid(ui, "probe_type", |ui| {
        let mut ch = row(ui, "Type", |ui| {
            combo(
                ui,
                "probe_mode",
                &mut p.mode,
                &ProbeMode::ALL,
                ProbeMode::label,
            )
        });
        if p.mode == ProbeMode::Realtime {
            ch |= row(ui, "Refresh Every (frames)", |ui| {
                ui.add(egui::DragValue::new(&mut p.refresh_interval).range(0..=600))
                    .on_hover_text("0 = only when Refresh Now is pressed")
                    .changed()
            });
            ch |= row(ui, "Time Slicing", |ui| {
                ui.checkbox(&mut p.time_slicing, "One face per frame")
                    .changed()
            });
        }
        ch
    });

    ui.label(RichText::new("Runtime Settings").strong());
    ch |= grid(ui, "probe_runtime", |ui| {
        let mut ch = row(ui, "Importance", |ui| {
            ui.add(egui::DragValue::new(&mut p.importance).range(-100..=100))
                .changed()
        });
        ch |= row(ui, "Intensity", |ui| {
            drag(ui, &mut p.intensity, 0.01, 0.0..=10.0)
        });
        ch |= row(ui, "Box Projection", |ui| {
            ui.checkbox(&mut p.box_projection, "").changed()
        });
        ch |= row(ui, "Blend Distance", |ui| {
            drag(ui, &mut p.blend_distance, 0.01, 0.0..=100.0)
        });
        ch
    });
    let mut size = p.size.to_array();
    if vec3_row(ui, "Box Size", &mut size, 0.05) {
        p.size = Vec3::from(size).max(Vec3::splat(0.01));
        ch = true;
    }
    let mut center = p.center.to_array();
    if vec3_row(ui, "Box Offset", &mut center, 0.05) {
        p.center = Vec3::from(center);
        ch = true;
    }
    let mut editing = state.probes.edit_bounds;
    if ui
        .toggle_value(&mut editing, "⬚ Edit Bounding Volume")
        .on_hover_text("Drag the face handles in the Scene view")
        .changed()
    {
        state.probes.edit_bounds = editing;
    }

    ui.label(RichText::new("Cubemap Capture Settings").strong());
    ch |= grid(ui, "probe_capture", |ui| {
        let mut ch = row(ui, "Resolution", |ui| {
            let mut ch = false;
            egui::ComboBox::from_id_salt("probe_res")
                .selected_text(p.resolution.to_string())
                .show_ui(ui, |ui| {
                    for r in RESOLUTIONS {
                        ch |= ui
                            .selectable_value(&mut p.resolution, r, r.to_string())
                            .changed();
                    }
                });
            ch
        });
        ch |= row(ui, "Clipping Near", |ui| {
            drag(ui, &mut p.near_clip, 0.01, 0.01..=100.0)
        });
        ch |= row(ui, "Clipping Far", |ui| {
            drag(ui, &mut p.far_clip, 1.0, 0.1..=1e5)
        });
        ch |= row(ui, "Clear Flags", |ui| {
            combo(
                ui,
                "probe_clear",
                &mut p.clear_flags,
                &ProbeClearFlags::ALL,
                ProbeClearFlags::label,
            )
        });
        if p.clear_flags == ProbeClearFlags::SolidColor {
            ch |= row(ui, "Background", |ui| color_rgb(ui, &mut p.background));
        }
        ch
    });

    ui.add_space(4.0);
    match p.mode {
        ProbeMode::Baked => {
            ui.weak(match &p.baked {
                Some(rel) => format!("Baked: {rel}"),
                None => "Not baked yet.".to_owned(),
            });
            let busy = state.probes.baking() || state.play.in_play_mode();
            if ui
                .add_enabled(!busy, egui::Button::new("Bake"))
                .on_hover_text("Bake every reflection probe in the scene")
                .clicked()
            {
                crate::probe_tools::start_bake(state);
            }
        }
        ProbeMode::Realtime => {
            if ui.button("Refresh Now").clicked() {
                state.probes.realtime.request(e.to_bits().get());
            }
        }
    }
    ch
}

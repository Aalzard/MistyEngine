//! Visual scripting: Script Graph assets (`.vgraph`, JSON) and the runtime that plays them.
//!
//! A graph is nodes joined by wires. White **exec** wires carry the flow of execution from an
//! event (Start, Update, a trigger, an input action, a custom event, a timer…) through flow
//! nodes (Branch, Sequence, loops, Delay…) and action nodes (Set Variable, engine calls).
//! Typed **data** wires carry values; nodes without exec pins are *pure* and are evaluated
//! lazily, when an action node that needs their value runs.
//!
//! A graph runs on a GameObject through its Scripts list, like a Lua script: the entry's path
//! ends in `.vgraph`. The Inspector shows it as a Script Graph component whose fields are the
//! graph's Object variables.
//!
//! Graphs are not turned into Lua. [`compile`] checks a graph (types, missing variables, cycles)
//! and turns it into a compact bytecode [`compile::Program`]: a flat list of ops over a register
//! file per instance, with pure nodes flattened into the action nodes that read them.
//! [`vm`] interprets it; [`runtime::GraphRuntime`] owns the instances, routes events to them and
//! holds the debugger state (breakpoints, stepping, the active wires and values the editor
//! shows while playing).
//!
//! Engine API nodes are generated by the editor from the Lua binding table (the one the Lua API
//! reference is generated from): an `Api` node names a Lua member (`Input.GetKey`,
//! `transform.position`, `rigidbody:AddForce`…). Common members run natively ([`api`]); the rest
//! call the Lua binding.
//!
//! **Subgraphs** are graphs with Graph Input and Graph Output nodes; a Subgraph node uses one,
//! either another `.vgraph` asset or a macro embedded in the graph file. They are inlined when
//! the graph compiles, so they cost nothing at run time and may contain flow and latent nodes.


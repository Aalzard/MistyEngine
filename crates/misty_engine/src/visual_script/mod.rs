/// File extension of Script Graph assets.
pub const EXTENSION: &str = "vgraph";
/// Current file version.
pub const VERSION: u32 = 1;

/// Is `path` a Script Graph asset?
pub fn is_graph_path(path: &str) -> bool {
    crate::assets::has_extension(path, &[EXTENSION])
}

/// Where a variable lives.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum VarScope {
    /// Private to one running graph (the Blackboard's Graph variables).
    #[default]
    Graph,
    /// Stored on the GameObject: shared with the object's other graphs and Lua scripts
    /// (`gameObject:GetVariable`), reachable from other objects, and set per object in the
    /// Inspector.
    Object,
}

/// A Blackboard variable.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Variable {
    pub name: String,
    #[serde(rename = "type")]
    pub ty: PinType,
    /// Starting value.
    pub value: Literal,
    #[serde(default, skip_serializing_if = "is_default")]
    pub scope: VarScope,
}

impl Variable {
    pub fn new(name: &str, ty: PinType, value: Literal) -> Self {
        Self {
            name: name.to_owned(),
            ty,
            value,
            scope: VarScope::Graph,
        }
    }

    pub fn object(mut self) -> Self {
        self.scope = VarScope::Object;
        self
    }
}

fn is_default<T: Default + PartialEq>(v: &T) -> bool {
    *v == T::default()
}

/// One node: its type, settings and the values typed into unconnected inputs.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Node {
    pub id: u32,
    /// Node type (`Branch`, `AddFloat`, `OnUpdate`, `Api`…).
    #[serde(rename = "type")]
    pub kind: String,
    pub position: [f32; 2],
    /// Settings that shape the node (variable name, event name, API member, pin counts…).
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub params: BTreeMap<String, String>,
    /// Values of unconnected inputs that differ from the pin defaults.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub values: BTreeMap<String, Literal>,
}

impl Node {
    pub fn param(&self, key: &str) -> &str {
        self.params.get(key).map_or("", String::as_str)
    }
}

/// A wire from one node's output to another node's input (exec or data).
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct Connection {
    pub from: u32,
    pub output: String,
    pub to: u32,
    pub input: String,
}

/// A text note on the canvas.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct StickyNote {
    pub position: [f32; 2],
    pub size: [f32; 2],
    pub text: String,
}

/// A titled frame around nodes.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Group {
    pub title: String,
    pub nodes: Vec<u32>,
}

/// A subgraph stored inside the graph file (a macro), used by Subgraph nodes with a `macro`
/// setting.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Macro {
    pub name: String,
    pub graph: ScriptGraph,
}

/// A Script Graph (`.vgraph`) or a macro's graph.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ScriptGraph {
    #[serde(default = "version")]
    pub version: u32,
    #[serde(default)]
    pub nodes: Vec<Node>,
    #[serde(default)]
    pub connections: Vec<Connection>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub variables: Vec<Variable>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub groups: Vec<Group>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub notes: Vec<StickyNote>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub macros: Vec<Macro>,
}

fn version() -> u32 {
    VERSION
}

impl Default for ScriptGraph {
    fn default() -> Self {
        Self {
            version: VERSION,
            nodes: Vec::new(),
            connections: Vec::new(),
            variables: Vec::new(),
            groups: Vec::new(),
            notes: Vec::new(),
            macros: Vec::new(),
        }
    }
}

/// Loads subgraph assets for Subgraph nodes.
pub trait Resolver {
    /// The graph at a project-relative path.
    fn load(&self, path: &str) -> Result<ScriptGraph, String>;
}

/// Reads subgraphs from a project folder (through the build's pak files when packed).
pub struct FileResolver(pub std::path::PathBuf);

impl Resolver for FileResolver {
    fn load(&self, path: &str) -> Result<ScriptGraph, String> {
        let file = crate::vfs::project_file(&self.0, path)?;
        let text = crate::vfs::read_to_string(file).map_err(|e| format!("{path}: {e}"))?;
        ScriptGraph::from_json(&text).map_err(|e| format!("{path}: {e}"))
    }
}

/// No subgraph assets (tests, graphs without Subgraph nodes).
pub struct NoFiles;

impl Resolver for NoFiles {
    fn load(&self, path: &str) -> Result<ScriptGraph, String> {
        Err(format!("{path}: subgraph assets are not available here"))
    }
}

impl ScriptGraph {
    /// A new graph (Create ▸ Visual Script Graph): Start and Update events to begin from.
    pub fn new_default() -> Self {
        let mut g = Self::default();
        g.add_node("OnStart", [0.0, 0.0]);
        g.add_node("OnUpdate", [0.0, 160.0]);
        g
    }

    pub fn from_json(text: &str) -> Result<Self, String> {
        serde_json::from_str(text).map_err(|e| e.to_string())
    }

    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("graph serializes")
    }

    pub fn load(path: &Path) -> Result<Self, String> {
        let text = crate::vfs::read_to_string(path).map_err(|e| e.to_string())?;
        Self::from_json(&text)
    }

    pub fn save(&self, path: &Path) -> Result<(), String> {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        std::fs::write(path, self.to_json() + "\n").map_err(|e| e.to_string())
    }

    pub fn node(&self, id: u32) -> Option<&Node> {
        self.nodes.iter().find(|n| n.id == id)
    }

    pub fn node_mut(&mut self, id: u32) -> Option<&mut Node> {
        self.nodes.iter_mut().find(|n| n.id == id)
    }

    pub fn variable(&self, name: &str) -> Option<&Variable> {
        self.variables.iter().find(|v| v.name == name)
    }

    pub fn macro_graph(&self, name: &str) -> Option<&ScriptGraph> {
        self.macros
            .iter()
            .find(|m| m.name == name)
            .map(|m| &m.graph)
    }

    pub fn next_id(&self) -> u32 {
        self.nodes.iter().map(|n| n.id + 1).max().unwrap_or(1)
    }

    /// Add a node of `kind` (no settings) and return its id.
    pub fn add_node(&mut self, kind: &str, position: [f32; 2]) -> u32 {
        self.add_node_with(kind, &[], position)
    }

    /// Add a node with settings and return its id.
    pub fn add_node_with(
        &mut self,
        kind: &str,
        params: &[(&str, &str)],
        position: [f32; 2],
    ) -> u32 {
        let id = self.next_id();
        self.nodes.push(Node {
            id,
            kind: kind.to_owned(),
            position,
            params: params
                .iter()
                .map(|(k, v)| ((*k).to_owned(), (*v).to_owned()))
                .collect(),
            values: BTreeMap::new(),
        });
        id
    }

    /// Set the value of an unconnected input.
    pub fn set_value(&mut self, node: u32, input: &str, value: Literal) {
        if let Some(n) = self.node_mut(node) {
            n.values.insert(input.to_owned(), value);
        }
    }

    /// Remove a node with its wires (and from groups).
    pub fn remove_node(&mut self, id: u32) {
        self.nodes.retain(|n| n.id != id);
        self.connections.retain(|c| c.from != id && c.to != id);
        for g in &mut self.groups {
            g.nodes.retain(|n| *n != id);
        }
    }

    /// Why `from.output` cannot be wired to `to.input` (None = it can).
    pub fn check_connection(
        &self,
        from: u32,
        output: &str,
        to: u32,
        input: &str,
        files: &dyn Resolver,
    ) -> Option<String> {
        if from == to {
            return Some("a node cannot connect to itself".into());
        }
        let (Some(a), Some(b)) = (self.node(from), self.node(to)) else {
            return Some("missing node".into());
        };
        let pa = ports(a, self, files);
        let pb = ports(b, self, files);
        let Some(out) = pa.output(output) else {
            return Some(format!("{} has no output '{output}'", a.kind));
        };
        let Some(inp) = pb.input(input) else {
            return Some(format!("{} has no input '{input}'", b.kind));
        };
        if !out.ty.connects_to(inp.ty) {
            return Some(format!(
                "{} cannot connect to {}",
                out.ty.label(),
                inp.ty.label()
            ));
        }
        None
    }

    /// Wire `from.output` to `to.input`. A data input takes one wire and an exec output starts
    /// one, so an existing wire there is replaced.
    pub fn connect(
        &mut self,
        from: u32,
        output: &str,
        to: u32,
        input: &str,
        files: &dyn Resolver,
    ) -> Result<(), String> {
        if let Some(e) = self.check_connection(from, output, to, input, files) {
            return Err(e);
        }
        let exec = self
            .node(from)
            .and_then(|n| ports(n, self, files).output(output).map(|p| p.ty))
            == Some(PinType::Exec);
        if exec {
            self.connections
                .retain(|c| !(c.from == from && c.output == output));
        } else {
            self.connections
                .retain(|c| !(c.to == to && c.input == input));
        }
        self.connections.push(Connection {
            from,
            output: output.to_owned(),
            to,
            input: input.to_owned(),
        });
        Ok(())
    }

    /// Remove every wire into `to.input` (or out of it, for an output).
    pub fn disconnect(&mut self, node: u32, port: &str, output: bool) {
        self.connections.retain(|c| {
            if output {
                !(c.from == node && c.output == port)
            } else {
                !(c.to == node && c.input == port)
            }
        });
    }

    /// The wire into `to.input`, if any.
    pub fn source(&self, to: u32, input: &str) -> Option<&Connection> {
        self.connections
            .iter()
            .find(|c| c.to == to && c.input == input)
    }

    /// Object variables (shown as Inspector fields).
    pub fn object_variables(&self) -> impl Iterator<Item = &Variable> {
        self.variables
            .iter()
            .filter(|v| v.scope == VarScope::Object)
    }

    /// Project assets the graph names (subgraphs, prefabs, clips in string values).
    pub fn referenced_assets(&self) -> Vec<String> {
        let mut out = Vec::new();
        let mut visit = |s: &str| {
            if s.starts_with("Assets/") && !out.iter().any(|x| x == s) {
                out.push(s.to_owned());
            }
        };
        for n in &self.nodes {
            for v in n.params.values() {
                visit(v);
            }
            for v in n.values.values() {
                if let Literal::String(s) = v {
                    visit(s);
                }
            }
        }
        out
    }
}

/// Fields the Inspector shows for a graph on an object: its Object variables (name, default).
pub fn inspect_fields(graph: &ScriptGraph) -> Vec<(String, crate::scene::ScriptValue)> {
    graph
        .object_variables()
        .filter_map(|v| Some((v.name.clone(), v.value.to_script_value(v.ty)?)))
        .collect()
}

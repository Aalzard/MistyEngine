/// The decal pass's WGSL for a set of graph functions: common code, the decal pass, the node
/// helpers, the graphs' functions (`sg_decal_<slot>`) and the `dc_graph` dispatch.
pub fn module_source(graphs: &[&crate::shader_graph::codegen::DecalGenerated]) -> String {
    let mut s = format!("{}\n{SRC}\n", super::pipelines::COMMON);
    s.push_str(crate::shader_graph::codegen::HELPERS);
    let mut seen: Vec<&str> = Vec::new();
    for g in graphs {
        for (name, text) in &g.functions {
            if !seen.contains(&name.as_str()) {
                seen.push(name);
                s.push_str(text);
                s.push('\n');
            }
        }
    }
    for g in graphs {
        s.push_str(&g.body);
    }
    s.push_str("fn dc_graph(slot: u32, input: DecalInput) -> DecalOutput {\n    switch slot {\n");
    for i in 0..graphs.len() {
        let _ = std::fmt::Write::write_fmt(
            &mut s,
            format_args!(
                "        case {}u: {{ return sg_decal_{}(input); }}\n",
                i + 1,
                i + 1
            ),
        );
    }
    s.push_str("        default: {\n            var o: DecalOutput;\n            o.normal = vec3<f32>(0.0, 0.0, 1.0);\n            return o;\n        }\n    }\n}\n");
    s
}

/// Parse and validate a decal module (`Err` = the message).
pub fn validate_module(src: &str) -> Result<(), String> {
    use wgpu::naga;
    let module = naga::front::wgsl::parse_str(src).map_err(|e| e.emit_to_string(src))?;
    naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::default(),
    )
    .validate(&module)
    .map_err(|e| e.emit_to_string(src))?;
    Ok(())
}

/// Validate one Decal graph's function (generated as `name`) in the decal pass.
pub fn validate_graph_named(
    g: &crate::shader_graph::codegen::DecalGenerated,
    name: &str,
) -> Result<(), String> {
    let mut one = g.clone();
    one.body = one.body.replacen(&format!("fn {name}("), "fn sg_decal_1(", 1);
    validate_module(&module_source(&[&one]))
}


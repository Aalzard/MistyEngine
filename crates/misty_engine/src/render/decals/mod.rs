/// `.mat` files and Decal graphs read for graph decals (re-read when their files change).
#[derive(Default)]
struct GraphAssets {
    materials: HashMap<String, (Option<std::time::SystemTime>, Option<crate::assets::Material>)>,
    graphs: HashMap<String, (Option<std::time::SystemTime>, Option<Arc<crate::shader_graph::ShaderGraph>>)>,
    last_check: Option<std::time::Instant>,
}

fn file_time(rel: &str) -> Option<std::time::SystemTime> {
    std::fs::metadata(crate::assets::absolute(rel))
        .and_then(|m| m.modified())
        .ok()
}

impl GraphAssets {
    /// Forget files that changed (checked at most twice a second).
    fn refresh(&mut self) {
        let now = std::time::Instant::now();
        if self
            .last_check
            .is_some_and(|t| now.duration_since(t).as_secs_f32() < 0.5)
        {
            return;
        }
        self.last_check = Some(now);
        self.materials.retain(|p, (t, _)| *t == file_time(p));
        self.graphs.retain(|p, (t, _)| *t == file_time(p));
    }

    fn material(&mut self, rel: &str) -> Option<crate::assets::Material> {
        self.materials
            .entry(rel.to_owned())
            .or_insert_with(|| {
                (
                    file_time(rel),
                    crate::assets::Material::load(&crate::assets::absolute(rel)).ok(),
                )
            })
            .1
            .clone()
    }

    fn graph(&mut self, rel: &str) -> Option<Arc<crate::shader_graph::ShaderGraph>> {
        self.graphs
            .entry(rel.to_owned())
            .or_insert_with(|| {
                (
                    file_time(rel),
                    crate::shader_graph::ShaderGraph::load(&crate::assets::absolute(rel))
                        .ok()
                        .map(Arc::new),
                )
            })
            .1
            .clone()
    }

    /// A projector's Decal graph material.
    fn resolve(&mut self, rel: &str) -> Option<(GraphDecal, Arc<crate::shader_graph::ShaderGraph>)> {
        let m = self.material(rel)?;
        if !crate::shader_graph::is_graph_path(&m.shader) {
            return None;
        }
        let g = self.graph(&m.shader)?;
        if g.target.material != crate::shader_graph::TargetMaterial::Decal {
            return None;
        }
        let keywords =
            crate::shader_graph::codegen::effective_keywords(&g, &crate::shader_graph::FileResolver);
        let variant: crate::shader_graph::Variant = keywords
            .iter()
            .map(|k| {
                let max = k.count() as u32 - 1;
                let v = m
                    .properties
                    .get(&k.name)
                    .and_then(crate::shader_asset::PropertyValue::as_float)
                    .map_or(k.default, |v| v.round().max(0.0) as u32)
                    .min(max);
                (k.name.clone(), v)
            })
            .collect();
        let mut values = g.default_values();
        for (k, v) in &m.properties {
            values.insert(k.clone(), v.clone());
        }
        Some((
            GraphDecal {
                shader: m.shader.clone(),
                variant: crate::shader_graph::variant_key(&keywords, &variant),
                values,
            },
            g,
        ))
    }
}

